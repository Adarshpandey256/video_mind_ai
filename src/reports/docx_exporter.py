"""Editable Word reports built with ``python-docx``.

The document uses real Word structure (Title/Heading styles, tables, bullet
lists, a header and a footer with page fields) rather than one giant paragraph,
so a reader can edit and re-style it normally. Long transcripts flow across
pages; nothing is dropped.

``python-docx`` is imported lazily so the application still starts when the
optional document libraries are not installed.
"""

from __future__ import annotations

import io
from typing import Any

from src.reports.export_types import RenderResult
from src.reports.report_models import (
    REPORT_SECTION_LABELS,
    ReportSection,
    VideoMindReport,
)

BODY_FONT = "Calibri"
UNICODE_FALLBACK_FONT = "Nirmala UI"


class DocxError(RuntimeError):
    """Raised when a Word document cannot be produced."""


def _docx():
    try:
        import docx  # noqa: PLC0415 - optional dependency, imported on demand
    except ImportError as error:  # pragma: no cover - depends on the environment
        raise DocxError(
            "Word export needs the python-docx package. Install it with "
            "`pip install python-docx` and restart the application."
        ) from error
    return docx


def _set_fonts(style: Any, *, size: float | None = None, bold: bool | None = None) -> None:
    """Apply a readable body font with a complex-script fallback for Devanagari."""
    from docx.oxml.ns import qn  # noqa: PLC0415

    style.font.name = BODY_FONT
    if size is not None:
        style.font.size = _docx().shared.Pt(size)
    if bold is not None:
        style.font.bold = bold
    rpr = style.element.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(fonts)
    fonts.set(qn("w:ascii"), BODY_FONT)
    fonts.set(qn("w:hAnsi"), BODY_FONT)
    fonts.set(qn("w:cs"), UNICODE_FALLBACK_FONT)


def _add_field(paragraph: Any, instruction: str) -> None:
    """Append a Word field (PAGE / NUMPAGES) to a paragraph."""
    from docx.oxml import OxmlElement  # noqa: PLC0415
    from docx.oxml.ns import qn  # noqa: PLC0415

    run = paragraph.add_run()
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    text = OxmlElement("w:instrText")
    text.set(qn("xml:space"), "preserve")
    text.text = instruction
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    run._r.append(begin)
    run._r.append(text)
    run._r.append(end)


def _configure_document(document: Any, report: VideoMindReport) -> None:
    """Set page margins, base styles, header and footer."""
    from docx.shared import Cm, Pt  # noqa: PLC0415

    for section in document.sections:
        section.top_margin = Cm(2.0)
        section.bottom_margin = Cm(2.0)
        section.left_margin = Cm(2.2)
        section.right_margin = Cm(2.2)

    normal = document.styles["Normal"]
    _set_fonts(normal, size=10.5)
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.15

    for name, size in (("Title", 26), ("Heading 1", 17), ("Heading 2", 13), ("Heading 3", 11.5)):
        style = document.styles[name]
        _set_fonts(style, size=size, bold=True)
        style.paragraph_format.space_before = Pt(14 if name != "Title" else 0)
        style.paragraph_format.space_after = Pt(6)
        style.paragraph_format.keep_with_next = True

    core = document.core_properties
    core.title = report.title
    core.subject = f"Video report for {report.video.title}"
    core.author = report.author or report.processing.app_name
    core.comments = "Generated by VideoMind AI from a stored transcript and summary."
    core.category = "Video report"

    header = document.sections[0].header.paragraphs[0]
    header.text = report.title
    header.style = document.styles["Header"]

    footer = document.sections[0].footer.paragraphs[0]
    footer.text = f"{report.processing.app_name} · {report.generated_at:%Y-%m-%d} · page "
    _add_field(footer, "PAGE")
    footer.add_run(" of ")
    _add_field(footer, "NUMPAGES")


def _add_metadata_table(document: Any, report: VideoMindReport) -> None:
    video = report.video
    rows = [
        ("Title", video.title),
        ("Source type", video.source_type.value),
        ("Original file", video.original_filename or "not recorded"),
        ("Source URL", video.source_url or "not available"),
        ("Duration", video.duration_label),
        ("Language", video.language or "not reported"),
        ("Transcribed with", video.transcription_model or "not recorded"),
        ("Recorded", video.created_at.isoformat() if video.created_at else "not recorded"),
        ("Transcript segments", str(video.segment_count)),
    ]
    table = document.add_table(rows=0, cols=2)
    table.style = "Table Grid"
    for label, value in rows:
        cells = table.add_row().cells
        cells[0].text = label
        cells[1].text = str(value)
        for paragraph in cells[0].paragraphs:
            for run in paragraph.runs:
                run.bold = True
    for row in table.rows:
        row.cells[0].width = _docx().shared.Cm(4.2)
        row.cells[1].width = _docx().shared.Cm(12.0)


def _add_paragraphs(document: Any, text: str) -> None:
    """Add prose, preserving paragraph boundaries instead of one giant block."""
    for block in str(text or "").split("\n\n"):
        cleaned = " ".join(block.split())
        if cleaned:
            document.add_paragraph(cleaned)


def _add_bullets(document: Any, items: list[str], *, style: str = "List Bullet") -> None:
    for item in items:
        document.add_paragraph(str(item), style=style)


def _italic(document: Any, text: str) -> Any:
    """Add an italic paragraph (italics live on runs, not on the paragraph)."""
    paragraph = document.add_paragraph(str(text))
    for run in paragraph.runs:
        run.italic = True
    return paragraph


def _section(document: Any, report: VideoMindReport, section: ReportSection, position: int) -> None:
    """Append one included section to the document."""
    heading = document.add_heading(f"{position}. {REPORT_SECTION_LABELS[section]}", level=1)
    if section in {ReportSection.TRANSCRIPT, ReportSection.CHAT_QA}:
        heading.paragraph_format.page_break_before = True

    if section is ReportSection.METADATA:
        _add_metadata_table(document, report)

    elif section is ReportSection.SUMMARY and report.summary is not None:
        summary = report.summary
        details = [f"Style: {summary.style}"]
        if summary.generated_at:
            details.append(f"Generated: {summary.generated_at.isoformat()}")
        if summary.model:
            details.append(f"Model: {summary.model}")
        _italic(document, " · ".join(details))
        if summary.partial_note:
            _italic(document, summary.partial_note)
        if summary.short_text and summary.short_text != summary.text:
            document.add_heading("In brief", level=2)
            _add_paragraphs(document, summary.short_text)
        if summary.text:
            _add_paragraphs(document, summary.text)

    elif section is ReportSection.KEY_TAKEAWAYS:
        for item in report.key_takeaways:
            paragraph = document.add_paragraph(style="List Bullet")
            run = paragraph.add_run(item.title)
            run.bold = True
            paragraph.add_run(f"  ({item.time_label})")
            if item.explanation:
                document.add_paragraph(item.explanation).paragraph_format.left_indent = (
                    _docx().shared.Cm(0.8)
                )
            if item.excerpt:
                quote = _italic(document, f'"{item.excerpt}"')
                quote.paragraph_format.left_indent = _docx().shared.Cm(0.8)

    elif section is ReportSection.TOPICS:
        for item in report.topics:
            paragraph = document.add_paragraph(style="List Bullet")
            paragraph.add_run(item.title).bold = True
            paragraph.add_run(f"  ({item.time_label})")
            if item.explanation:
                document.add_paragraph(item.explanation)
            if item.key_points:
                _add_bullets(document, item.key_points, style="List Bullet 2")

    elif section is ReportSection.CHAPTERS:
        for item in report.chapters:
            paragraph = document.add_paragraph(style="List Bullet")
            paragraph.add_run(item.title).bold = True
            paragraph.add_run(f"  ({item.time_label})")
            if item.description:
                document.add_paragraph(item.description)
            if item.major_points:
                _add_bullets(document, item.major_points, style="List Bullet 2")

    elif section is ReportSection.ACTION_ITEMS:
        for item in report.action_items:
            marker = "Action" if item.kind == "action" else "Decision"
            details = ", ".join(part for part in (item.owner, item.deadline) if part)
            paragraph = document.add_paragraph(style="List Bullet")
            paragraph.add_run(f"{marker}: ").bold = True
            paragraph.add_run(item.text)
            if details:
                paragraph.add_run(f" ({details})")
            paragraph.add_run(f"  [{item.time_label}]")
            if item.context:
                _italic(document, item.context)

    elif section is ReportSection.TRANSCRIPT:
        if not report.transcript:
            document.add_paragraph("No transcript was included.")
            return
        if not report.timestamps_available:
            _italic(
                document,
                "This transcript has no timestamps, so no time ranges are shown.",
            )
        for entry in report.transcript:
            paragraph = document.add_paragraph()
            if report.shows_timestamps:
                stamp = paragraph.add_run(f"[{entry.time_label}] ")
                stamp.bold = True
            paragraph.add_run(entry.text)

    elif section is ReportSection.CHAT_QA:
        if not report.chat:
            document.add_paragraph("No chatbot questions were included.")
            return
        for position_in_chat, entry in enumerate(report.chat, start=1):
            document.add_heading(f"Question {position_in_chat}", level=2)
            document.add_paragraph(entry.question).bold = True
            document.add_paragraph(entry.answer)
            if entry.citations:
                document.add_paragraph("Sources").bold = True
                for citation in entry.citations:
                    label = citation.source_name or "Untitled recording"
                    item = document.add_paragraph(style="List Bullet")
                    item.add_run(f"[{citation.source_ref}] {label}").bold = True
                    item.add_run(
                        f" · {citation.kind_label} · {citation.time_label}"
                    )
                    if citation.quote:
                        quote = _italic(document, f'"{citation.quote}"')
                        quote.paragraph_format.left_indent = _docx().shared.Cm(0.8)
            else:
                _italic(
                    document,
                    "No resolved source citations were recorded for this answer.",
                )
            for note in entry.notes:
                _italic(document, f"Note: {note}")

    elif section is ReportSection.SOURCES:
        if not report.sources:
            document.add_paragraph("No chatbot source passages are available.")
            return
        for source in report.sources:
            item = document.add_paragraph(style="List Bullet")
            item.add_run(f"[{source.source_ref}] {source.label}").bold = True
            item.add_run(f" · {source.kind_label} · {source.time_label}")
            _italic(document, f'"{source.excerpt}"')

    elif section is ReportSection.PROCESSING:
        processing = report.processing
        rows = [
            ("Generated by", processing.app_name),
            ("Application version", processing.app_version or "not recorded"),
            ("Generated at", processing.generated_at.isoformat()),
            ("Transcript segments", str(processing.transcript_segments)),
            ("Transcription model", processing.transcript_model or "not recorded"),
            ("Summary style", processing.summary_style or "not included"),
            ("Chat answers", str(processing.chat_answers)),
            (
                "Timestamps",
                "available from the transcript"
                if processing.timestamps_available
                else "not available",
            ),
            ("Report schema", report.schema_version),
        ]
        table = document.add_table(rows=0, cols=2)
        table.style = "Table Grid"
        for label, value in rows:
            cells = table.add_row().cells
            cells[0].text = label
            cells[1].text = str(value)
        if processing.notes:
            document.add_heading("Notes", level=2)
            _add_bullets(document, processing.notes)


def build_docx(report: VideoMindReport) -> RenderResult:
    """Render the report as an editable .docx document."""
    docx = _docx()
    document = docx.Document()
    _configure_document(document, report)

    document.add_paragraph(report.processing.app_name.upper(), style="Subtitle")
    document.add_heading(report.title, level=0)

    meta_lines = []
    if report.author:
        meta_lines.append(f"Prepared by: {report.author}")
    if report.organisation:
        meta_lines.append(f"Organisation: {report.organisation}")
    meta_lines.append(f"Generated: {report.generated_at.isoformat()}")
    meta_lines.append(f"Report schema: {report.schema_version}")
    for line in meta_lines:
        document.add_paragraph(line)

    if report.notes:
        document.add_heading("Notes", level=1)
        _add_paragraphs(document, report.notes)

    position = 0
    for section in (item for item in ReportSection if item in report.sections):
        position += 1
        _section(document, report, section, position)

    if report.omitted_sections:
        document.add_heading("Sections not included", level=1)
        for entry in report.omitted_sections:
            label = REPORT_SECTION_LABELS[entry.section]
            document.add_paragraph(
                f"{label}: {entry.reason or 'no data available'}", style="List Bullet"
            )

    document.add_paragraph()
    _italic(document, f"Generated by {report.processing.app_name}.")

    buffer = io.BytesIO()
    try:
        document.save(buffer)
    except Exception as error:  # noqa: BLE001 - translated into an export error
        raise DocxError(
            "The Word document could not be written. Try a smaller report or another format."
        ) from error
    return RenderResult(data=buffer.getvalue())


__all__ = ["DocxError", "build_docx"]
